#!/usr/bin/env bash
# =============================================================================
# help.sh — Help system: usage info and per-command documentation
# =============================================================================

# Program version
ZIVPN_MANAGER_VERSION="1.6.1"

# ---------------------------------------------------------------------------
# show_version — Print version
# ---------------------------------------------------------------------------
show_version() {
    echo "zivpn-manager v${ZIVPN_MANAGER_VERSION}"
}

# ---------------------------------------------------------------------------
# show_usage — Quick usage summary (shown on invalid command)
# ---------------------------------------------------------------------------
show_usage() {
    echo ""
    echo -e "${BOLD}ZiVPN Account Manager v${ZIVPN_MANAGER_VERSION}${RESET}"
    echo ""
    echo -e "${BOLD}Penggunaan:${RESET}"
    echo "  zivpn-manager                  Buka menu interaktif (TUI)"
    echo "  zivpn-manager <perintah>       Jalankan perintah langsung"
    echo "  zivpn-manager help             Tampilkan bantuan lengkap"
    echo "  zivpn-manager help <perintah>  Bantuan untuk perintah tertentu"
    echo ""
    echo -e "${BOLD}Perintah yang tersedia:${RESET}"
    echo ""
    echo -e "  ${GREEN}Manajemen Akun:${RESET}"
    echo "    list           Lihat daftar semua akun"
    echo "    add            Tambah akun baru"
    echo "    delete         Hapus akun"
    echo "    trial          Buat akun trial (durasi pendek)"
    echo "    extend         Perpanjang masa aktif akun"
    echo "    set-expired    Set tanggal expired akun"
    echo "    domain         Set atau hapus custom domain"
    echo ""
    echo -e "  ${CYAN}Backup & Restore:${RESET}"
    echo "    backup         Buat backup data (akun, config, sertifikat)"
    echo "    restore        Restore data dari file backup"
    echo "    backups        Lihat daftar file backup"
    echo ""
    echo -e "  ${GRAY}Service & Info:${RESET}"
    echo "    status         Lihat status service ZiVPN"
    echo "    restart        Restart service ZiVPN"
    echo "    info           Lihat info server dan konfigurasi"
    echo ""
    echo -e "  ${GRAY}Lainnya:${RESET}"
    echo "    help           Tampilkan bantuan ini"
    echo "    help <cmd>     Bantuan detail untuk perintah tertentu"
    echo "    update         Cek dan install update dari GitHub"
    echo "    uninstall      Hapus ZiVPN dan semua data dari server"
    echo "    version        Tampilkan versi"
    echo "    expire-check   Cek & nonaktifkan akun expired (untuk cron)"
    echo ""
    echo -e "Contoh: ${CYAN}zivpn-manager add${RESET}"
    echo -e "        ${CYAN}zivpn-manager help backup${RESET}"
    echo ""
}

