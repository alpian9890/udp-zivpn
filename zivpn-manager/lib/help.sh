# ---------------------------------------------------------------------------
# show_help — Main help handler (dispatch)
# ---------------------------------------------------------------------------
show_help() {
    local topic="${1:-}"
    if [[ -z "$topic" ]]; then
        show_usage
    else
        show_help_topic "$topic"
    fi
}
